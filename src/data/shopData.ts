export const getAffiliateConfig = (): AffiliateConfig => {
  try {
    const raw = localStorage.getItem(AFFILIATE_CONFIG_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      return {
        ...DEFAULT_AFFILIATE_CONFIG,
        ...parsed,
        amazonTag: parsed.amazonTag || DEFAULT_AFFILIATE_CONFIG.amazonTag,
        amazonJpTag: parsed.amazonJpTag || DEFAULT_AFFILIATE_CONFIG.amazonJpTag,
        amazonEuTag: parsed.amazonEuTag || DEFAULT_AFFILIATE_CONFIG.amazonEuTag,
        amazonUkTag: parsed.amazonUkTag || DEFAULT_AFFILIATE_CONFIG.amazonUkTag,
      };
    }
  } catch (e) {
    // ignore
  }
  return { ...DEFAULT_AFFILIATE_CONFIG };
};

export const saveAffiliateConfig = (config: AffiliateConfig): void => {
  try {
    localStorage.setItem(AFFILIATE_CONFIG_KEY, JSON.stringify(config));
  } catch (e) {
    // ignore
  }
};

export const buildProductAffiliateUrl = (
  product: ShopProduct,
  region: MarketplaceRegion = 'us'
): string => {
  const config = getAffiliateConfig();

  if (region === 'jp') {
    const tag = config.amazonJpTag || 'ptcgpocket-jp-22';

    if (product.targetUrlJp) {
      try {
        const parsed = new URL(product.targetUrlJp);
        parsed.searchParams.set('tag', tag);
        return parsed.toString();
      } catch {
        return product.targetUrlJp;
      }
    }

    if (product.asinJp) {
      return `https://www.amazon.co.jp/dp/${product.asinJp}?tag=${encodeURIComponent(tag)}`;
    }

    // Only route to amazon.co.jp if the product's targetUrl is explicitly on amazon.co.jp
    if (product.targetUrl && product.targetUrl.includes('amazon.co.jp')) {
      try {
        const parsed = new URL(product.targetUrl);
        parsed.searchParams.set('tag', tag);
        return parsed.toString();
      } catch {
        return product.targetUrl;
      }
    }

    // If the product belongs to US/global marketplace (like Silver Buffalo or Cable Guys) and has no JP ASIN,
    // do NOT force it to amazon.co.jp (which causes 404 dog page errors). Fall through to US handler below!
  }

  if (region === 'de') {
    const tag = config.amazonEuTag || 'ptcgpocket-de-21';
    const asin = product.asinEu;
    if (asin) {
      return `https://www.amazon.de/dp/${asin}?tag=${encodeURIComponent(tag)}`;
    }
    if (product.targetUrl && product.targetUrl.includes('amazon.de')) {
      try {
        const parsed = new URL(product.targetUrl);
        parsed.searchParams.set('tag', tag);
        return parsed.toString();
      } catch {
        return product.targetUrl;
      }
    }
  }

  if (region === 'uk') {
    const tag = config.amazonUkTag || 'ptcgpocket-uk-21';
    const asin = product.asinUk;
    if (asin) {
      return `https://www.amazon.co.uk/dp/${asin}?tag=${encodeURIComponent(tag)}`;
    }
    if (product.targetUrl && product.targetUrl.includes('amazon.co.uk')) {
      try {
        const parsed = new URL(product.targetUrl);
        parsed.searchParams.set('tag', tag);
        return parsed.toString();
      } catch {
        return product.targetUrl;
      }
    }
  }

  // Default / US Region (amazon.com)
  const tag = config.amazonTag || 'ptcgpocket-20';

  // 1. If product explicitly has targetUrl, ALWAYS honor it and ensure affiliate tag is attached
  if (product.targetUrl) {
    try {
      const parsed = new URL(product.targetUrl);
      parsed.searchParams.set('tag', tag);
      return parsed.toString();
    } catch {
      return product.targetUrl.includes('?')
        ? `${product.targetUrl}&tag=${tag}`
        : `${product.targetUrl}?tag=${tag}`;
    }
  }

  // 2. Fallback to asin dp link if available
  if (product.asin) {
    return `https://www.amazon.com/dp/${product.asin}?tag=${encodeURIComponent(tag)}`;
  }

  return `https://www.amazon.com?tag=${tag}`;
};

